<#
.SYNOPSIS
Downloads the display fonts for repository names and generates the page's font files.

.DESCRIPTION
The page is one HTML string and cannot load anything from the network, so the
fonts travel inside it. This script fetches each font's Latin .woff2 files and
licence from pinned npm packages into apps/devpanel/assets/fonts/, then writes:

  apps/devpanel/web/fonts.css  @font-face rules with the files as base64 data
  apps/devpanel/web/fonts.js   the catalogue the page picks from

Both outputs are committed, so building DevPanel needs neither this script nor
the network. Run it again only to change the font set; files already
downloaded are reused. Every font is under the SIL Open Font License 1.1.

.EXAMPLE
pwsh scripts/build-fonts.ps1
#>
param(
    # Download again even when a file is already in assets/fonts.
    [switch] $Refresh
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$assets = Join-Path $root 'apps/devpanel/assets/fonts'
$web = Join-Path $root 'apps/devpanel/web'
$cdn = 'https://cdn.jsdelivr.net/npm'
$fontsource = '5.3.0'

# id, family name, theme, weights (all upright), weights that also have a real italic.
$fonts = @(
    @{ id = 'press-start-2p'; family = 'Press Start 2P'; theme = 'pixel'; weights = 400 }
    @{ id = 'silkscreen'; family = 'Silkscreen'; theme = 'pixel'; weights = 400, 700 }
    @{ id = 'vt323'; family = 'VT323'; theme = 'pixel'; weights = 400 }
    @{ id = 'pixelify-sans'; family = 'Pixelify Sans'; theme = 'pixel'; weights = 400, 700 }
    @{ id = 'orbitron'; family = 'Orbitron'; theme = 'cyber'; weights = 400, 700, 900 }
    @{ id = 'audiowide'; family = 'Audiowide'; theme = 'cyber'; weights = 400 }
    @{ id = 'oxanium'; family = 'Oxanium'; theme = 'cyber'; weights = 400, 700 }
    @{ id = 'share-tech-mono'; family = 'Share Tech Mono'; theme = 'tech'; weights = 400 }
    @{ id = 'chakra-petch'; family = 'Chakra Petch'; theme = 'tech'; weights = 400, 700; italics = 400, 700 }
    @{ id = 'michroma'; family = 'Michroma'; theme = 'tech'; weights = 400 }
    @{ id = 'tektur'; family = 'Tektur'; theme = 'tech'; weights = 400, 700 }
    @{ id = 'major-mono-display'; family = 'Major Mono Display'; theme = 'tech'; weights = 400 }
    @{ id = 'dseg14'; family = 'DSEG14 Classic'; theme = 'chip'; weights = 400, 700; italics = 400, 700; package = 'dseg@0.46.0' }
)

function Get-Asset([string] $url, [string] $path) {
    if ($Refresh -or -not (Test-Path $path)) {
        Write-Host "  $url"
        Invoke-WebRequest -Uri $url -OutFile $path
    }
}

function Get-FaceUrl($font, [int] $weight, [bool] $italic) {
    if ($font.package) {
        # DSEG names its files by style rather than by number.
        $style = @{ '400' = 'Regular'; '700' = 'Bold' }["$weight"]
        if ($italic) { $style = if ($weight -eq 400) { 'Italic' } else { 'BoldItalic' } }
        return "$cdn/$($font.package)/fonts/DSEG14-Classic/DSEG14Classic-$style.woff2"
    }
    $style = if ($italic) { 'italic' } else { 'normal' }
    "$cdn/@fontsource/$($font.id)@$fontsource/files/$($font.id)-latin-$weight-$style.woff2"
}

New-Item -ItemType Directory -Force -Path $assets, (Join-Path $assets 'licences') | Out-Null
$css = [System.Text.StringBuilder]::new()
[void] $css.AppendLine('/* Generated by scripts/build-fonts.ps1 from apps/devpanel/assets/fonts. Do not edit. */')
$catalogue = @()
foreach ($font in $fonts) {
    Write-Host $font.family
    $licence = if ($font.package) { "$cdn/$($font.package)/DSEG-LICENSE.txt" } else { "$cdn/@fontsource/$($font.id)@$fontsource/LICENSE" }
    Get-Asset $licence (Join-Path $assets "licences/$($font.id).txt")
    $faces = foreach ($weight in $font.weights) {
        @{ weight = $weight; italic = $false }
        if ($font.italics -contains $weight) { @{ weight = $weight; italic = $true } }
    }
    foreach ($face in $faces) {
        $suffix = if ($face.italic) { 'italic' } else { 'normal' }
        $file = Join-Path $assets "$($font.id)-$($face.weight)-$suffix.woff2"
        Get-Asset (Get-FaceUrl $font $face.weight $face.italic) $file
        $data = [Convert]::ToBase64String([IO.File]::ReadAllBytes($file))
        [void] $css.AppendLine("@font-face { font-family: 'dp-$($font.id)'; font-weight: $($face.weight); font-style: $suffix; font-display: block; src: url(data:font/woff2;base64,$data) format('woff2'); }")
    }
    $catalogue += [ordered]@{
        id = $font.id; family = $font.family; theme = $font.theme
        weights = @($font.weights); italics = @($font.italics | Where-Object { $_ })
    }
}

Set-Content -Encoding utf8 -NoNewline -Path (Join-Path $web 'fonts.css') -Value $css.ToString()
$json = ConvertTo-Json -InputObject $catalogue -Depth 4 -Compress
$js = "// Generated by scripts/build-fonts.ps1. Do not edit. Each font's faces are in fonts.css as 'dp-<id>'.`nconst FONTS = $json;`n"
Set-Content -Encoding utf8 -NoNewline -Path (Join-Path $web 'fonts.js') -Value $js
$size = (Get-Item (Join-Path $web 'fonts.css')).Length
Write-Host ("Wrote fonts.css ({0:N0} KB) and fonts.js for {1} fonts" -f ($size / 1KB), $fonts.Count)
